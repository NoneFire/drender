// Published `sql` fences are display-only for the renderer, so execute them here:
// a report that quotes a check query must be able to run it against its own database.
function verifyPublishedSql(name, markdown, databasePath) {
  const fences = [...markdown.matchAll(/```sql([^\n]*)\n([\s\S]*?)```/g)];
  if (fences.length === 0) return 0;
  const database = new DatabaseSync(databasePath, { readOnly: true });
  try {
    for (const [index, fence] of fences.entries()) {
      const info = fence[1] ?? '';
      const dialect = /dialect=([A-Za-z0-9_-]+)/.exec(info)?.[1] ?? 'standard';
      if (dialect !== 'sqlite') {
        console.log(`  ${name}: skipped ${dialect} SQL fence ${index + 1} (only sqlite fences are executed)`);
        continue;
      }
      const statement = fence[2] ?? '';
      let rows;
      try {
        rows = database.prepare(statement).all();
      } catch (error) {
        throw new Error(`${name} publishes a SQL fence that does not run against ${config2path(databasePath)}: ${error.message}\n${statement.trim()}`);
      }
      const title = /title="([^"]*)"/.exec(info)?.[1] ?? `fence ${index + 1}`;
      console.log(`  ${name}: SQL "${title}" returned ${rows.length} rows`);
      if (rows.length === 0) throw new Error(`${name} publishes a SQL fence that returns no rows: ${title}`);
    }
  } finally {
    database.close();
  }
  return fences.length;
}

const config2path = (databasePath) => databasePath.replace(workspaceRoot + '/', '');

for (const { name, markdown, config, databasePath } of examples) {
  verifyPublishedSql(name, markdown, databasePath);
  const sourcePath = databasePath;
  const queryFiles = await readQueryFiles(config);
  const { datasets, scenes } = loadMarkdownSqliteSources(config, sourcePath, { queryFiles });
  const document = { markdown, datasets, scenes };
  const validation = validateReport(document);
  if (!validation.valid) {
    throw new Error(`${name} failed validation:\n${validation.diagnostics.map((item) => `${item.code} line ${item.line}: ${item.message}`).join('\n')}`);
  }
  const rendered = await renderReport(document, renderOptions);
  await writeFile(resolve(exampleDirectory, `${name}.html`), rendered.html, 'utf8');
  console.log(`${name}: wrote ${rendered.bytes} bytes (${validation.diagnostics.length} warnings)`);
}

