async function readQueryFiles(config) {
  const paths = [...new Set([
    ...Object.values(config.datasets ?? {}).map((source) => source.queryFile),
    ...Object.values(config.scenes ?? {}).map((source) => source.queryFile),
  ].filter((path) => typeof path === 'string'))];
  return Object.fromEntries(await Promise.all(paths.map(async (path) => {
    if (path.startsWith('/') || /^[A-Za-z]:/.test(path) || /[\\\u0000-\u001f\u007f]/.test(path)
      || path.split('/').some((part) => !part || part === '.' || part === '..') || !/\.sql$/i.test(path)) {
      throw new Error(`Invalid workspace-relative SQL file path: ${path}`);
    }
    const filePath = resolve(workspaceRoot, path);
    return [path, await readFile(filePath, 'utf8')];
  })));
}

